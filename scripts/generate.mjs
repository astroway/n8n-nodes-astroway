// Builds nodes/Astroway/operations.generated.ts from the live OpenAPI spec.
// Run before a release: `npm run generate`. The node never reads the spec at
// execute time; field schemas are loaded at design time by the node itself.
import { writeFileSync } from 'node:fs';

const SPEC_URL = 'https://api.astroway.info/v1/openapi.json';
const METHODS = ['get', 'post', 'put', 'patch', 'delete'];
// Not callable with a plain key from a workflow, or not JSON.
const EXCLUDED_TAGS = new Set([
	'System',
	'Embeddable Widgets',
	'Real-time Streaming',
	'MCP Advanced',
	'Agent Platform',
	'White-label',
	'Webhooks',
]);
const EXCLUDED_PATH = /^\/(mcp|embed|stream|keys|auth|site-keys)(\/|$)/;

const res = await fetch(SPEC_URL, { headers: { 'User-Agent': 'n8n-nodes-astroway-generator' } });
if (!res.ok) throw new Error(`spec answered ${res.status}`);
const spec = await res.json();

const deref = (x) => {
	for (let i = 0; x && x.$ref && i < 10; i++) {
		x = x.$ref.replace('#/', '').split('/').reduce((a, k) => a[k], spec);
	}
	return x;
};

const slug = (s) =>
	s
		.toLowerCase()
		.replace(/&/g, 'and')
		.replace(/[^a-z0-9]+/g, '-')
		.replace(/^-|-$/g, '');

const oneLine = (s, max = 200) => {
	const t = (s ?? '').replace(/\s+/g, ' ').trim();
	const first = t.match(/^.*?[.!?](\s|$)/)?.[0].trim() ?? t;
	return first.length > max ? `${first.slice(0, max - 1).trimEnd()}…` : first;
};

const resources = new Map();
const operations = [];
for (const [path, item] of Object.entries(spec.paths)) {
	if (EXCLUDED_PATH.test(path)) continue;
	for (const method of METHODS) {
		const op = item[method];
		if (!op) continue;
		const tag = op.tags?.[0] ?? 'Other';
		if (EXCLUDED_TAGS.has(tag)) continue;
		const ct = op.responses?.['200'] && deref(op.responses['200']).content;
		if (ct && !ct['application/json']) continue;
		const params = [...(item.parameters ?? []), ...(op.parameters ?? [])].map(deref);
		const resource = slug(tag);
		resources.set(resource, tag);
		operations.push({
			resource,
			value: `${method.toUpperCase()} ${path}`,
			name: (op.summary ?? `${method.toUpperCase()} ${path}`).trim(),
			description: oneLine(op.description ?? op.summary),
			method: method.toUpperCase(),
			path,
			query: params.filter((p) => p.in === 'query').map((p) => p.name),
			pathParams: params.filter((p) => p.in === 'path').map((p) => p.name),
			hasBody: Boolean(op.requestBody),
		});
	}
}

// n8n's linter wants options sorted by name; names must also be unique per resource.
operations.sort((a, b) => a.resource.localeCompare(b.resource) || a.name.localeCompare(b.name));
const seen = new Set();
for (const op of operations) {
	let key = `${op.resource}|${op.name}`;
	if (seen.has(key)) op.name = `${op.name} (${op.method} ${op.path})`;
	key = `${op.resource}|${op.name}`;
	if (seen.has(key)) throw new Error(`duplicate operation name ${key}`);
	seen.add(key);
}
const resourceList = [...resources.entries()]
	.map(([value, name]) => ({ value, name }))
	.sort((a, b) => a.name.localeCompare(b.name));

const operationProperties = resourceList.map((r) => {
	const ops = operations.filter((op) => op.resource === r.value);
	return {
		displayName: 'Operation',
		name: 'operation',
		type: 'options',
		noDataExpression: true,
		displayOptions: { show: { resource: [r.value] } },
		options: ops.map((op) => ({ name: op.name, value: op.value, description: op.description, action: op.name })),
		default: ops[0].value,
	};
});
const routes = Object.fromEntries(
	operations.map((op) => [op.value, { method: op.method, path: op.path, query: op.query, pathParams: op.pathParams, hasBody: op.hasBody }]),
);

const out = `// Generated by scripts/generate.mjs from ${SPEC_URL} (${spec.info?.version ?? 'unknown'}). Do not edit.
import type { INodeProperties } from 'n8n-workflow';

export interface AstrowayRoute {
	method: 'GET' | 'POST' | 'PUT' | 'PATCH' | 'DELETE';
	path: string;
	query: string[];
	pathParams: string[];
	hasBody: boolean;
}

export const resourceProperty: INodeProperties = ${JSON.stringify(
	{
		displayName: 'Resource',
		name: 'resource',
		type: 'options',
		noDataExpression: true,
		options: resourceList,
		default: 'core',
	},
	null,
	'\t',
)};

export const operationProperties: INodeProperties[] = ${JSON.stringify(operationProperties, null, '\t')};

export const ROUTES: Record<string, AstrowayRoute> = ${JSON.stringify(routes, null, '\t')};
`;
writeFileSync(new URL('../nodes/Astroway/operations.generated.ts', import.meta.url), out);
console.log(`${resourceList.length} resources, ${operations.length} operations`);
